# -*- coding: utf-8 -*-
"""Step 7, work item 7.2 -- the GRAMMAR side of `G7.10`.

`G7.10` compares two independently written recognisers for the same language on
10,000 sampled strings. `4thJ_step7_grammar.py:validate_record()` is one of them,
written by hand as a procedural checker. This module is the other: it emits an
**EBNF** the XGrammar back-end compiles and matches with, and it is written from
the language definition rather than from the checker.

🔴 **This module must never import `validate_record`.** If the two sides shared
code, `G7.10` would compare a thing to itself -- the `V5.d` / `V6.b` failure
class the parent document names explicitly. The only thing shared is
`build_alphabets()`, which is the constraint DEFINITION both sides are compiled
from; sharing that is the point, sharing the recogniser is the bug.

The 1440-minute sum is carried by the 145-state tally automaton written out as
145 nonterminals, `S0`..`S144`. That is what makes `RL12`'s regularity objection
answerable: the constraint is not arithmetic performed at match time, it is a
finite state set anyone can count in the emitted text.
"""

import importlib
import os
import random
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)

_grammar = importlib.import_module("4thJ_step7_grammar")

DAY_MINUTES = _grammar.DAY_MINUTES
SLOT_MINUTES = _grammar.SLOT_MINUTES
N_TALLY_STATES = _grammar.N_TALLY_STATES          # 145
COP_MIN, COP_MAX = _grammar.COP_MIN, _grammar.COP_MAX
LOC_ALPHABET = _grammar.LOC_ALPHABET
N_PREFIX_FIELDS = _grammar.N_PREFIX_FIELDS        # 6

#: The characters a prefix field may contain. NOT arbitrary bytes: the shipped
#: prefixes carry `75+` and `11-14`, so `+` and `-` are in the class and dropping
#: either would reject real conditioning strings. Declared here because the
#: sampler draws from exactly this class -- a mismatch between the two would
#: register as a grammar disagreement when it is really a test artefact.
PREFIX_CHARS = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ_+-"
PREFIX_CLASS_EBNF = "[0-9a-zA-Z_+-]"


class EbnfError(ValueError):
    pass


def _lit(s):
    return '"' + s + '"'


def build_ebnf(alphabets, whole_record=True):
    """Return the EBNF text for the diary language, built from `alphabets`.

    Deliberately plain BNF: alternation, concatenation, one character class, and
    right recursion for the prefix fields. No `*`, no `?`, no optional groups.
    Every back-end reads this dialect the same way, and `G7.10`'s job is to find
    disagreements about the LANGUAGE, not about EBNF sugar.

    🔴 `whole_record` picks the ROOT, and it is not cosmetic -- see `FINDING 80`.
    `True` is the WHOLE RECORD, prefix included, and it is what the oracle checks
    and what `G7.10` compares. `False` is the COMPLETION ONLY, `S0 "<eor>"`, and
    it is what a decoder must be given: at generation time the prefix and its `|`
    are already in the PROMPT, so a mask rooted at the whole record starts matching
    the episodes against `PF`. `PFCHAR` is `[0-9a-zA-Z_+-]` and `PF` is unbounded,
    so that mask is satisfied by arbitrary word-like text and constrains nothing.
    """
    act = sorted(alphabets["act"])
    act2 = sorted(alphabets["act2"])
    loc = sorted(alphabets["loc"])
    cop = sorted(alphabets["cop"])

    if not act or not act2 or not loc or not cop:
        raise EbnfError("empty alphabet: act=%d act2=%d loc=%d cop=%d"
                        % (len(act), len(act2), len(loc), len(cop)))
    if set(loc) != set(LOC_ALPHABET):
        raise EbnfError("LOC alphabet drifted from the module constant: %s" % sorted(loc))

    lines = []
    lines.append("# 4J Step 7 diary grammar -- generated by 4thJ_step7_ebnf.py.")
    lines.append("# ACT %d | ACT2 %d | LOC %d | COP %d | tally states %d"
                 % (len(act), len(act2), len(loc), len(cop), N_TALLY_STATES))
    lines.append("")

    # --- the record -------------------------------------------------------
    if whole_record:
        pf = ' "," '.join(["PF"] * N_PREFIX_FIELDS)
        lines.append('root ::= %s "|" S0 "<eor>"' % pf)
        lines.append('PF ::= PFCHAR | PFCHAR PF')
        lines.append('PFCHAR ::= %s' % PREFIX_CLASS_EBNF)
    else:
        lines.insert(2, '# ROOT: COMPLETION ONLY. The prefix and its "|" are in the prompt.')
        lines.append('root ::= S0 "<eor>"')
    lines.append("")

    # --- terminal alphabets ----------------------------------------------
    lines.append("ACT ::= " + " | ".join(_lit(c) for c in act))
    lines.append("ACT2 ::= " + " | ".join(_lit(c) for c in act2))
    lines.append("LOC ::= " + " | ".join(_lit(c) for c in loc))
    lines.append("COP ::= " + " | ".join(_lit(str(c)) for c in cop))
    lines.append("")

    # --- one episode, minus its duration ----------------------------------
    # ACT2 may be empty -- `validate_record` accepts `act2 == ""`. Written as two
    # explicit alternatives rather than an optional group, so the empty case is
    # visible in the text instead of hidden in a `?`.
    lines.append('TAIL ::= "," ACT ",," LOC "," COP ";" '
                 '| "," ACT "," ACT2 "," LOC "," COP ";"')
    lines.append("")

    # --- 144 duration-carrying episode rules ------------------------------
    for k in range(1, N_TALLY_STATES):
        lines.append('E%d ::= "%d" TAIL' % (k, k * SLOT_MINUTES))
    lines.append("")

    # --- the 145-state tally ----------------------------------------------
    # S_s means "s slots already spent". A day is complete only on reaching 144,
    # so `S144` is never defined: the last episode of every accepting derivation
    # is the bare `E{144-s}` alternative. That is also why zero episodes cannot
    # parse -- `S0` has no empty production.
    for s in range(0, N_TALLY_STATES - 1):
        alts = ["E%d S%d" % (k, s + k) for k in range(1, N_TALLY_STATES - 1 - s)]
        alts.append("E%d" % (N_TALLY_STATES - 1 - s))
        lines.append("S%d ::= %s" % (s, " | ".join(alts)))

    return "\n".join(lines) + "\n"


