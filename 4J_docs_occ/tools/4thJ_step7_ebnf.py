def _out_of_alphabet(alphabet, width):
    """A code of the given width that is provably NOT in the alphabet.

    🔴 Computed, never chosen. The first run of the Step 7 self-test shipped `999`
    and `99` as "invalid" codes and both turned out to be REAL, so two negative
    cases proved nothing (`V4.f` vacuity). This searches instead of guessing, and
    raises rather than returning a code it could not prove absent.
    """
    for n in range(10 ** width):
        c = str(n).zfill(width)
        if c not in alphabet:
            return c
    raise EbnfError("every %d-digit code is in the alphabet; no negative case exists" % width)


def _random_prefix(rng):
    fields = []
    for _ in range(N_PREFIX_FIELDS):
        n = rng.randint(1, 8)
        fields.append("".join(rng.choice(PREFIX_CHARS) for _ in range(n)))
    return ",".join(fields)


def _random_durations(rng):
    """A partition of 1440 into positive multiples of 10."""
    k = rng.randint(1, 40)
    k = min(k, N_TALLY_STATES - 1)
    cuts = sorted(rng.sample(range(1, N_TALLY_STATES - 1), k - 1)) if k > 1 else []
    prev, out = 0, []
    for c in cuts + [N_TALLY_STATES - 1]:
        out.append((c - prev) * SLOT_MINUTES)
        prev = c
    return out


def _random_episode(rng, alphabets, dur):
    act = rng.choice(sorted(alphabets["act"]))
    act2 = "" if rng.random() < 0.3 else rng.choice(sorted(alphabets["act2"]))
    loc = rng.choice(sorted(alphabets["loc"]))
    cop = rng.choice(sorted(alphabets["cop"]))
    return "%d,%s,%s,%s,%d;" % (dur, act, act2, loc, cop)


def _valid_record(rng, alphabets):
    eps = "".join(_random_episode(rng, alphabets, d) for d in _random_durations(rng))
    return "%s|%s<eor>" % (_random_prefix(rng), eps)


def _split_episodes(text):
    body = text[: -len("<eor>")]
    prefix, eps = body.split("|", 1)
    chunks = eps.split(";")[:-1]
    return prefix, chunks


def _rejoin(prefix, chunks):
    return "%s|%s<eor>" % (prefix, "".join(c + ";" for c in chunks))


# Each mutator takes (valid_text, rng, alphabets) and returns a mutated string.
# Named so the report can say which class produced a disagreement.
def _mutators(alphabets):
    bad_act = _out_of_alphabet(alphabets["act"], 3)
    bad_act2 = _out_of_alphabet(alphabets["act2"], 2)

    def m_whitespace(t, rng, _a):
        i = rng.randint(0, len(t) - 1)
        return t[:i] + rng.choice(" \t\n") + t[i:]

    def m_no_eor(t, _r, _a):
        return t[: -len("<eor>")]

    def m_no_bar(t, _r, _a):
        return t.replace("|", "", 1)

    def m_prefix_short(t, _r, _a):
        p, c = _split_episodes(t)
        return _rejoin(",".join(p.split(",")[:-1]), c)

    def m_prefix_long(t, _r, _a):
        p, c = _split_episodes(t)
        return _rejoin(p + ",extra", c)

    def m_prefix_empty(t, rng, _a):
        p, c = _split_episodes(t)
        f = p.split(",")
        f[rng.randrange(len(f))] = ""
        return _rejoin(",".join(f), c)

    def m_zero_episodes(t, _r, _a):
        p, _c = _split_episodes(t)
        return "%s|<eor>" % p

    def m_no_terminal_semi(t, _r, _a):
        p, c = _split_episodes(t)
        return "%s|%s<eor>" % (p, "".join(x + ";" for x in c)[:-1])

    def m_episode_short(t, rng, _a):
        p, c = _split_episodes(t)
        i = rng.randrange(len(c))
        c[i] = ",".join(c[i].split(",")[:-1])
        return _rejoin(p, c)

    def m_episode_long(t, rng, _a):
        p, c = _split_episodes(t)
        i = rng.randrange(len(c))
        c[i] = c[i] + ",9"
        return _rejoin(p, c)

    def m_dur_not_mult10(t, rng, _a):
        p, c = _split_episodes(t)
        i = rng.randrange(len(c))
        f = c[i].split(",")
        f[0] = str(int(f[0]) + rng.randint(1, 9))
        c[i] = ",".join(f)
        return _rejoin(p, c)

    def m_dur_leading_zero(t, rng, _a):
        p, c = _split_episodes(t)
        i = rng.randrange(len(c))
        f = c[i].split(",")
        f[0] = "0" + f[0]
        c[i] = ",".join(f)
        return _rejoin(p, c)

    def m_day_short(t, rng, _a):
        p, c = _split_episodes(t)
        if len(c) == 1:
            f = c[0].split(",")
            f[0] = str(int(f[0]) - SLOT_MINUTES) if int(f[0]) > SLOT_MINUTES else "10"
            c[0] = ",".join(f)
            return _rejoin(p, c)
        return _rejoin(p, c[:-1])

    def m_day_long(t, rng, _a):
        p, c = _split_episodes(t)
        return _rejoin(p, c + [c[rng.randrange(len(c))]])

    def m_bad_act(t, rng, _a):
        p, c = _split_episodes(t)
        i = rng.randrange(len(c))
        f = c[i].split(",")
        f[1] = bad_act
        c[i] = ",".join(f)
        return _rejoin(p, c)

    def m_bad_act2(t, rng, _a):
        p, c = _split_episodes(t)
        i = rng.randrange(len(c))
        f = c[i].split(",")
        f[2] = bad_act2
        c[i] = ",".join(f)
        return _rejoin(p, c)

    def m_bad_loc(t, rng, _a):
        p, c = _split_episodes(t)
        i = rng.randrange(len(c))
        f = c[i].split(",")
        f[3] = "workplace"        # the class Step 2 does not emit -- see D-S7-2
        c[i] = ",".join(f)
        return _rejoin(p, c)

    def m_cop_range(t, rng, _a):
        p, c = _split_episodes(t)
        i = rng.randrange(len(c))
        f = c[i].split(",")
        f[4] = str(COP_MAX + 1 + rng.randint(0, 30))
        c[i] = ",".join(f)
        return _rejoin(p, c)

    def m_cop_leading_zero(t, rng, _a):
        p, c = _split_episodes(t)
        i = rng.randrange(len(c))
        f = c[i].split(",")
        f[4] = "0" + f[4]
        c[i] = ",".join(f)
        return _rejoin(p, c)

    return [
        ("whitespace", m_whitespace), ("no_eor", m_no_eor), ("no_bar", m_no_bar),
        ("prefix_short", m_prefix_short), ("prefix_long", m_prefix_long),
        ("prefix_empty", m_prefix_empty), ("zero_episodes", m_zero_episodes),
        ("no_terminal_semi", m_no_terminal_semi),
        ("episode_short", m_episode_short), ("episode_long", m_episode_long),
        ("dur_not_mult10", m_dur_not_mult10), ("dur_leading_zero", m_dur_leading_zero),
        ("day_short", m_day_short), ("day_long", m_day_long),
        ("bad_act", m_bad_act), ("bad_act2", m_bad_act2), ("bad_loc", m_bad_loc),
        ("cop_range", m_cop_range), ("cop_leading_zero", m_cop_leading_zero),
    ]


def sample_strings(alphabets, n=10000, seed=20260822, valid_share=0.5):
    """Return [(label, text)] -- reproducible for a given seed.

    `V7.e`: the set must contain known-invalid strings. Half the sample is
    mutated on purpose, every mutator class appears, and the caller is expected
    to check that the oracle actually rejects some of them rather than assuming
    a mutation is a rejection.
    """
    rng = random.Random(seed)
    muts = _mutators(alphabets)
    out = []
    n_valid = int(n * valid_share)
    for _ in range(n_valid):
        out.append(("valid", _valid_record(rng, alphabets)))
    for i in range(n - n_valid):
        name, fn = muts[i % len(muts)]
        base = _valid_record(rng, alphabets)
        try:
            out.append((name, fn(base, rng, alphabets)))
        except Exception as e:                     # a mutator that cannot fire is a gap
            out.append(("MUTATOR_FAILED:%s:%s" % (name, type(e).__name__), base))
    rng.shuffle(out)
    return out


